-- V16: modalidade da execucao (planilha SEEU) e providencias com prazo.

ALTER TABLE execucoes_penais
    ADD COLUMN modalidade varchar(30) NOT NULL DEFAULT 'ABERTO',
    ADD COLUMN data_distribuicao date;

ALTER TABLE execucoes_penais
    ADD CONSTRAINT execucoes_penais_modalidade_check CHECK (modalidade IN
        ('ABERTO','SEMIABERTO','FECHADO','LIVRAMENTO_CONDICIONAL','PRD','TRATAMENTO_AMBULATORIAL'));

-- tratamento ambulatorial nao tem pena nem termino calculavel
ALTER TABLE execucoes_penais
    ALTER COLUMN pena_total_dias DROP NOT NULL,
    ALTER COLUMN data_termino_original DROP NOT NULL,
    ALTER COLUMN data_termino_prevista DROP NOT NULL,
    ALTER COLUMN origem_calculo DROP NOT NULL;

ALTER TABLE execucoes_penais
    ADD CONSTRAINT execucoes_penais_pena_por_modalidade CHECK (
        modalidade = 'TRATAMENTO_AMBULATORIAL'
        OR (pena_total_dias IS NOT NULL AND data_termino_original IS NOT NULL
            AND data_termino_prevista IS NOT NULL AND origem_calculo IS NOT NULL));

CREATE TABLE providencias_execucao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execucao_penal_id bigint NOT NULL REFERENCES execucoes_penais(id),
    tipo varchar(40) NOT NULL,
    descricao varchar(500),
    prazo date,
    prioritaria boolean NOT NULL DEFAULT false,
    concluida_em date,
    registrado_por varchar(100) NOT NULL,
    concluida_por varchar(100),
    criado_em timestamp(6) NOT NULL
);

CREATE INDEX idx_providencia_pendente_prazo
    ON providencias_execucao (prazo) WHERE concluida_em IS NULL;
CREATE INDEX idx_providencia_execucao ON providencias_execucao (execucao_penal_id);
